#!/usr/bin/env python3
"""
Emit a PRE-CONFIGURED copy of the iPad Scriptable script.

Why: typing a camera password on a tablet keyboard in front of the client is the
single most likely thing to go wrong on site. This bakes the settings in, so the
on-site procedure is "import file, tap System check, tap Log a donation", with no
password to type and no settings screens.

Reads the camera from CAMERA_URL, CAMERA_USER and CAMERA_PASS, or from
SECRETS.local.md (gitignored) when they are unset, plus APERTURE_DEVICE_TOKEN from
the environment (the same value set on Vercel), and writes:

    camera-access/ipad/Aperture.local.js      <- gitignored, CONTAINS THE PASSWORD

Transfer it to the iPad by AirDrop (or iCloud Drive > Scriptable). Never commit
it, never email it.

Usage:  APERTURE_DEVICE_TOKEN=... python3 scripts/make-ipad-script.py
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SOURCE = REPO / "camera-access" / "ipad" / "aperture-pull.js"
TARGET = REPO / "camera-access" / "ipad" / "Aperture.local.js"
SECRETS = REPO / "SECRETS.local.md"

RELAY = "https://<vercel-app-host>/api/donate"
LOCATION = "Cul2vate, Ellington Ag Center"
SNAPSHOT_PATH = "/ISAPI/Streaming/channels/101/picture"


def camera() -> tuple[str, str, str]:
    """CAMERA_URL, CAMERA_USER and CAMERA_PASS from the environment, else SECRETS.local.md."""
    env = [os.environ.get(k, "").strip() for k in ("CAMERA_URL", "CAMERA_USER", "CAMERA_PASS")]
    if all(env):
        return env[0].rstrip("/"), env[1], env[2]
    if not SECRETS.exists():
        sys.exit(f"ERROR: export CAMERA_URL, CAMERA_USER and CAMERA_PASS, or create {SECRETS.name} (gitignored).")
    secrets = SECRETS.read_text()
    ip = re.search(r"LAN:\s*`(\d+\.\d+\.\d+\.\d+)`", secrets)
    creds = re.search(r"user\s+`([^`]+)`\s*/\s*pass\s+`([^`]+)`", secrets)
    if not ip or not creds:
        sys.exit("ERROR: could not read the camera IP / admin credentials out of SECRETS.local.md.")
    return f"http://{ip.group(1)}", creds.group(1), creds.group(2)


def main() -> None:
    base, user, password = camera()
    device_token = os.environ.get("APERTURE_DEVICE_TOKEN", "")

    js = SOURCE.read_text()
    block = re.search(r"const CONFIG = \{.*?\n\};", js, re.S)
    if not block:
        sys.exit("ERROR: CONFIG block not found in aperture-pull.js.")

    configured = (
        "const CONFIG = {\n"
        f"  base: {json.dumps(base)},\n"
        f"  user: {json.dumps(user)},\n"
        f"  pass: {json.dumps(password)},\n"
        f"  path: {json.dumps(SNAPSHOT_PATH)},\n"
        f"  relay: {json.dumps(RELAY)},\n"
        f"  exportUrl: {json.dumps(RELAY.replace('/api/donate', '/api/export'))},\n"
        f"  voidUrl: {json.dumps(RELAY.replace('/api/donate', '/api/void'))},\n"
        f"  deviceToken: {json.dumps(device_token)},\n"
        f"  location: {json.dumps(LOCATION)},\n"
        "  maxPixels: 1600,\n"
        "};"
    )
    out = js[: block.start()] + configured + js[block.end():]

    header = (
        "// ============================================================\n"
        "// PRE-CONFIGURED BUILD — CONTAINS THE CAMERA PASSWORD.\n"
        "// Generated by scripts/make-ipad-script.py. Gitignored on purpose.\n"
        "// Do not commit, email, or post this file. Regenerate instead.\n"
        "// ============================================================\n"
    )
    TARGET.write_text(header + out)
    TARGET.chmod(0o600)

    # Fail loudly rather than hand over a file that would not work on site.
    check = TARGET.read_text()
    problems = []
    if f"base: {json.dumps(base)}" not in check:
        problems.append("camera address not baked in")
    if 'pass: ""' in check:
        problems.append("password placeholder still empty")
    # The literal must read back as the exact password, or digest auth fails on the dock.
    baked = re.search(r"^  pass: (.*),$", check, re.M)
    if not baked or json.loads(baked.group(1)) != password:
        problems.append("password did not survive quoting")
    if f"relay: {json.dumps(RELAY)}" not in check:
        problems.append("relay URL missing")
    if "buildDigestAuth" not in check:
        problems.append("digest auth code missing")
    if problems:
        sys.exit("ERROR: generated file is not usable: " + "; ".join(problems))

    # Refuse to hand over a build that is not actually runnable. `node --check` alone
    # has already let functionless files reach the device.
    import subprocess
    check = REPO / "scripts" / "check-ipad-script.sh"
    if check.exists():
        result = subprocess.run(["bash", str(check), str(TARGET)], capture_output=True, text=True)
        if result.returncode != 0:
            TARGET.unlink(missing_ok=True)
            sys.exit("ERROR: generated build failed verification (deleted):\n" + result.stdout + result.stderr)
        print("verified: " + result.stdout.strip().splitlines()[-1])

    print(f"wrote  {TARGET.relative_to(REPO)}  ({TARGET.stat().st_size // 1024} KB, mode 600)")
    print(f"  camera : {base}  user={user}  pass={'*' * len(password)}")
    print(f"  relay  : {RELAY}")
    print(f"  token  : {'set' if device_token else 'NOT SET (works only while the relay is open)'}")
    print("\nAirDrop this file to the iPad, open it in Scriptable, rename it to 'Aperture'.")
    print("Then run System check from its menu (camera-access/ipad/ONSITE-CARD.md).")


if __name__ == "__main__":
    main()
